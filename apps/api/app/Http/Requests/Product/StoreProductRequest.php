<?php

namespace App\Http\Requests\Product;

use App\Enums\ProductStatus;
use App\Support\CurrentOrganization;
use App\Support\ExternalId;
use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

class StoreProductRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    /**
     * The SKU and external id uniqueness checks include soft-deleted products, matching the
     * unique (organization_id, sku) and (organization_id, external_id) indexes.
     *
     * @return array<string, list<mixed>>
     */
    public function rules(CurrentOrganization $current): array
    {
        return [
            'id' => ['prohibited'],
            'organization_id' => ['prohibited'],
            'name' => ['required', 'string', 'max:255'],
            'sku' => [
                'nullable',
                'string',
                'max:64',
                Rule::unique('products', 'sku')->where('organization_id', $current->organization->id),
            ],
            'price' => ['required', 'numeric', 'decimal:0,2', 'min:0', 'max:9999999999.99'],
            'status' => ['sometimes', Rule::enum(ProductStatus::class)],
            'external_id' => [
                'nullable',
                ...ExternalId::rules(),
                Rule::unique('products', 'external_id')->where('organization_id', $current->organization->id),
            ],
        ];
    }

    /**
     * @return array<string, string>
     */
    public function messages(): array
    {
        return [
            'id.prohibited' => 'The id is generated by the server.',
            'organization_id.prohibited' => 'The organization is taken from the X-Organization-Id context and cannot be set in the payload.',
            'sku.unique' => 'This SKU is already used by another product in this organization, including deleted products.',
            'external_id.regex' => 'The external id may only contain letters, numbers, dots, underscores, colons and hyphens.',
            'external_id.unique' => 'This external id is already used by another product in this organization, including deleted products.',
        ];
    }
}
